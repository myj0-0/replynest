import test from "node:test";
import assert from "node:assert/strict";
import pg from "pg";
import { migrateSharedWechatStore, recordSharedWechatEvent, resolveSharedWechatDelivery, type VerifiedSharedEvent } from "./shared-wechat-store.js";
import { sceneToken } from "./shared-wechat-routing.js";

test("isolated PostgreSQL: concurrent callback dedup, fixed destination and fail-closed gates", { skip: !process.env.SHARED_WECHAT_TEST_DATABASE_URL }, async () => {
  const db = new pg.Pool({ connectionString: process.env.SHARED_WECHAT_TEST_DATABASE_URL });
  try {
    // Must be a fresh disposable test database, never the application database.
    await db.query(`CREATE TABLE tenants(tenant_id TEXT PRIMARY KEY,name TEXT NOT NULL,status TEXT NOT NULL,chatwoot_account_id BIGINT UNIQUE)`);
    await db.query(`INSERT INTO tenants VALUES('a','Merchant A','test',11),('b','Merchant B','test',22)`);
    await migrateSharedWechatStore(db);
    await db.query(`INSERT INTO shared_wechat_accounts VALUES('app',TRUE)`);
    await db.query(`INSERT INTO shared_wechat_enrollments VALUES('app','a',TRUE),('app','b',TRUE)`);
    const a = sceneToken(), b = sceneToken();
    for (const [tenant, token] of [["a",a],["b",b]] as const) await db.query(`INSERT INTO shared_wechat_scenes VALUES('app',$1,$2,NOW()+INTERVAL '10 minutes',FALSE)`,[token.digest,tenant]);
    const base = Date.now() - 20000;
    const event = (id: string, offset: number): VerifiedSharedEvent => ({ appId: "app",openId:"user",eventId:id,occurredAt:base+offset,kind:"text",text:"customer message" });
    const scanA: VerifiedSharedEvent = {...event("scan-a",0),kind:"scan",event:"subscribe",eventKey:`qrscene_${a.value}`,text:undefined};
    const entries = await Promise.all([recordSharedWechatEvent(db,scanA),recordSharedWechatEvent(db,scanA)]);
    assert.equal(entries.filter(e=>e.duplicate).length,1);
    assert.equal(entries[0].decision.action,"entered");
    const message = event("message-a",1000);
    assert.equal((await recordSharedWechatEvent(db,message)).decision.tenantId,"a");
    const second = await recordSharedWechatEvent(db,{...event("scan-b",2000),kind:"scan",event:"SCAN",eventKey:b.value,text:undefined});
    assert.equal(second.decision.action,"choose");
    const code = second.decision.state.choices!.items.find(c=>c.tenantId==="b")!.code;
    assert.equal((await recordSharedWechatEvent(db,{...event("select-b",3000),text:`选择 ${code}`})).decision.tenantId,"b");
    assert.equal((await recordSharedWechatEvent(db,event("message-b",4000))).decision.tenantId,"b");
    const media:VerifiedSharedEvent={...event('image-b',4500),kind:'media',text:'[公众号消息] 图片',media:{kind:'image',mediaId:'safe-media'}};
    assert.equal((await recordSharedWechatEvent(db,media)).decision.tenantId,'b');
    assert.equal((await recordSharedWechatEvent(db,media)).duplicate,true);
    await assert.rejects(recordSharedWechatEvent(db,{...media,media:{kind:'image',mediaId:'altered'}}),/shared_event_conflict/);
    assert.equal((await db.query("SELECT media_payload->>'mediaId' id FROM shared_wechat_receipts WHERE event_id='image-b'")).rows[0].id,'safe-media');
    await assert.rejects(resolveSharedWechatDelivery(db,"app","message-a"),/shared_delivery_not_ready/);
    await db.query(`INSERT INTO shared_wechat_inboxes VALUES('app','a',11,101,TRUE),('app','b',22,202,TRUE)`);
    await db.query("UPDATE shared_wechat_accounts SET default_tenant_id='a' WHERE app_id='app'");
    const generic={...event('generic-entry',0),openId:'new-user',kind:'scan' as const,event:'subscribe',eventKey:undefined,text:undefined};
    const greeting=await recordSharedWechatEvent(db,generic);assert.equal(greeting.decision.action,'info');assert.equal(greeting.decision.tenantId,'a');
    assert.equal((await recordSharedWechatEvent(db,generic)).duplicate,true);
    await assert.rejects(resolveSharedWechatDelivery(db,'app','generic-entry'),/shared_delivery_not_ready/);
    const firstText={...event('first-default-text',1000),openId:'new-user'};
    assert.equal((await recordSharedWechatEvent(db,firstText)).decision.tenantId,'a');
    assert.equal((await resolveSharedWechatDelivery(db,'app','first-default-text')).tenantId,'a');
    const service=await recordSharedWechatEvent(db,{...event('service',2000),openId:'new-user',kind:'service',event:'CLICK',eventKey:'RN_SERVICE_INTRO',text:undefined});
    assert.equal(service.decision.action,'info');
    await assert.rejects(resolveSharedWechatDelivery(db,'app','service'),/shared_delivery_not_ready/);
    const invalid=await recordSharedWechatEvent(db,{...generic,eventId:'invalid-generic',openId:'bad-scene',eventKey:'qrscene_expired'});
    assert.equal(invalid.decision.reason,'invalid_scene');
    assert.equal((await recordSharedWechatEvent(db,{...event('invalid-followup',1000),openId:'bad-scene'})).decision.tenantId,undefined);
    const deliveryA = await resolveSharedWechatDelivery(db,"app","message-a");
    const deliveryB = await resolveSharedWechatDelivery(db,"app","message-b");
    assert.equal(deliveryA.tenantId,"a"); assert.equal(deliveryA.accountId,"11"); assert.equal(deliveryA.inboxId,"101");
    assert.equal(deliveryB.tenantId,"b"); assert.equal(deliveryB.accountId,"22"); assert.equal(deliveryB.inboxId,"202");
    await assert.rejects(resolveSharedWechatDelivery(db,"other-app","message-a"),/shared_delivery_not_ready/);
    await assert.rejects(resolveSharedWechatDelivery(db,"app","scan-a"),/shared_delivery_not_ready/);
    await assert.rejects(db.query(`UPDATE shared_wechat_inboxes SET account_id=11,inbox_id=101 WHERE tenant_id='b'`),/unique constraint/);
    await db.query(`UPDATE shared_wechat_inboxes SET account_id=99 WHERE tenant_id='a'`);
    await assert.rejects(resolveSharedWechatDelivery(db,"app","message-a"),/shared_delivery_not_ready/);
    await db.query(`UPDATE shared_wechat_inboxes SET account_id=11,enabled=FALSE WHERE tenant_id='a'`);
    await assert.rejects(resolveSharedWechatDelivery(db,"app","message-a"),/shared_delivery_not_ready/);
    await db.query(`UPDATE shared_wechat_inboxes SET enabled=TRUE WHERE tenant_id='a'`);
    const replay = await recordSharedWechatEvent(db,message);
    assert.equal(replay.duplicate,true); assert.equal(replay.decision.tenantId,"a");
    await assert.rejects(recordSharedWechatEvent(db,{...message,text:"altered replay"}),/shared_event_conflict/);
    await db.query(`UPDATE shared_wechat_enrollments SET enabled=FALSE WHERE tenant_id='b'`);
    await assert.rejects(resolveSharedWechatDelivery(db,"app","message-b"),/shared_delivery_not_ready/);
    assert.equal((await resolveSharedWechatDelivery(db,"app","message-a")).tenantId,"a");
    assert.equal((await recordSharedWechatEvent(db,event("after-disable",5000))).decision.action,"choose");
    const rows = await db.query(`SELECT destination_tenant_id,delivery_state FROM shared_wechat_receipts WHERE event_id='message-a'`);
    assert.deepEqual(rows.rows[0],{destination_tenant_id:"a",delivery_state:"held"});
    await db.query(`UPDATE shared_wechat_accounts SET enabled=FALSE`);
    await assert.rejects(resolveSharedWechatDelivery(db,"app","message-a"),/shared_delivery_not_ready/);
    await assert.rejects(recordSharedWechatEvent(db,event("disabled-account",6000)),/shared_account_disabled/);
    assert.equal((await db.query(`SELECT COUNT(*)::int AS count FROM shared_wechat_receipts WHERE event_id='disabled-account'`)).rows[0].count,0);
  } finally { await db.end(); }
});
